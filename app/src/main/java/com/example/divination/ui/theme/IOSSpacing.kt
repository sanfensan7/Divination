package com.example.divination.ui.theme

import androidx.compose.ui.unit.dp

/**
 * iOS 间距系统
 * 
 * 定义了符合 Apple 人机界面指南（HIG）的标准间距值。
 * 这些间距用于创建一致的布局和视觉节奏。
 */
object IOSSpacing {
    // 基础间距单位
    /** 超小间距 - 4dp */
    val XXSmall = 4.dp
    
    /** 特小间距 - 8dp */
    val XSmall = 8.dp
    
    /** 小间距 - 12dp */
    val Small = 12.dp
    
    /** 中等间距 - 16dp */
    val Medium = 16.dp
    
    /** 大间距 - 20dp */
    val Large = 20.dp
    
    /** 特大间距 - 24dp */
    val XLarge = 24.dp
    
    /** 超大间距 - 32dp */
    val XXLarge = 32.dp
    
    /** 巨大间距 - 48dp */
    val XXXLarge = 48.dp
    
    // 页面边距
    /** 页面水平边距 - 20dp */
    val PageHorizontal = 20.dp
    
    /** 页面垂直边距 - 16dp */
    val PageVertical = 16.dp
    
    // 卡片间距
    /** 卡片内边距 - 16dp */
    val CardPadding = 16.dp
    
    /** 卡片外边距 - 12dp */
    val CardMargin = 12.dp
    
    // 列表间距
    /** 列表项间距 - 12dp */
    val ListItemSpacing = 12.dp
    
    /** 列表分区间距 - 24dp */
    val ListSectionSpacing = 24.dp
    
    // 组件间距
    /** 组件间距 - 16dp */
    val ComponentSpacing = 16.dp
}
