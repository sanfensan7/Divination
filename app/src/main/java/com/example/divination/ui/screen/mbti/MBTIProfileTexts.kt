    fun getProfile(type: String): Profile {
        return when (type.uppercase()) {
            "INTJ" -> intj
            "INTP" -> intp
            "ENTJ" -> entj
            "ENTP" -> entp
            "INFJ" -> infj
            "INFP" -> infp
            "ENFJ" -> enfj
            "ENFP" -> enfp
            "ISTJ" -> istj
            "ISFJ" -> isfj
            "ESTJ" -> estj
            "ESFJ" -> esfj
            "ISTP" -> istp
            "ISFP" -> isfp
            "ESTP" -> estp
            "ESFP" -> esfp
            else -> generic(type)
        }
    }

